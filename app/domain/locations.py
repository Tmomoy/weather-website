class InvalidLocation(ValueError):
    pass


def normalize_location(value: str) -> str:
    location = "".join((value or "").strip().split()).replace("台", "臺")
    if not location:
        raise InvalidLocation("請輸入縣市或行政區名稱。")
    if location in DISTRICT_TO_COUNTY:
        return DISTRICT_TO_COUNTY[location]
    if location in COUNTIES:
        return location
    if not location.endswith(("市", "縣")):
        candidate = location + ("市" if location in CITY_NAMES else "縣")
        if candidate in COUNTIES:
            return candidate
    raise InvalidLocation("找不到這個地區，請選擇臺灣的縣市或行政區。")
